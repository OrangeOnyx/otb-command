/* Concierge grounding context — regenerate with `npm run concierge-context`
   whenever src/data/*.json changes. Runs the export-package generator (the
   single source of dossier truth), then wraps the full-financials dossier MD
   into api/_context.mjs so the Vercel function ships it inside its bundle.
   The output module IS committed (same pattern as src/data/heights.json). */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// The dossier's "how to use" blockquote targets humans pasting into a chat UI;
// the concierge system prompt frames the context itself, so drop that block.
// Exported so test/generated-freshness re-derives with the SAME rule.
export const trimDossier = md =>
  md.replace(/\n> \*\*How to use this file:\*\*[^\n]*\n/, "\n");

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  execFileSync(process.execPath, [join(root, "tools/export-package.mjs")], { stdio: "inherit" });
  const trimmed = trimDossier(readFileSync(join(root, "export/OTB-Property-Dossier.md"), "utf8"));
  mkdirSync(join(root, "api"), { recursive: true });
  writeFileSync(
    join(root, "api/_context.mjs"),
    "/* GENERATED by tools/build-concierge-context.mjs — do not hand-edit.\n" +
    "   Regenerate with `npm run concierge-context` after src/data changes. */\n" +
    "export const CONTEXT = " + JSON.stringify(trimmed) + ";\n"
  );
  console.log("api/_context.mjs written:", trimmed.length, "chars");
}
