/* A-8 facade openings (2026-10-02, operator: "the front of the stores have a unique charm that
   Floorplanner was able to capture"). Reads the Floorplanner twin's openings
   (public/twin/model-data.json — door voids and window proxies with real widths/heights),
   maps each through the twin's own registration into A-1 plan px, and keeps the ones on an
   exterior face. Output: src/data/facade-openings.json. Re-run after the twin is rebuilt:
     node tools/build-facade-openings.mjs                                                   */
import fs from "node:fs";
import { modelToPlan } from "../src/lib/styled-twin-plan.js";

const root = new URL("../", import.meta.url);
const md = JSON.parse(fs.readFileSync(new URL("public/twin/model-data.json", root)));
const M = JSON.parse(fs.readFileSync(new URL("public/twin/site-context.json", root))).registration.matrix3x2;

// Exterior faces in A-1 plan px (same anchors the A-8 plan frame builds on).
const FACES = [
  { id: "long-front", axis: "y", at: 292.56, span: [150, 1130], tol: 6 },
  { id: "long-rear", axis: "y", at: 131.35, span: [150, 1130], tol: 6 },
  { id: "long-west", axis: "x", at: 160.78, span: [125, 300], tol: 6 },
  { id: "short-front", axis: "x", at: 1154.51, span: [215, 615], tol: 6 },
  { id: "short-rear", axis: "x", at: 1310.94, span: [215, 615], tol: 6 },
  { id: "short-south", axis: "y", at: 612.95, span: [1150, 1315], tol: 20 }
];
const round = n => Math.round(n * 100) / 100;
const out = [];
for (const o of md.openings) {
  const [x, y] = modelToPlan([o.position[0], o.position[2]], M);
  const f = FACES.find(f => {
    const [d, s] = f.axis === "y" ? [y, x] : [x, y];
    return Math.abs(d - f.at) < f.tol && s > f.span[0] && s < f.span[1];
  });
  if (!f) continue;
  out.push({
    id: o.id, face: f.id, type: o.type,
    along: round(f.axis === "y" ? x : y),        // plan px along the face
    widthFt: round(o.widthMeters / 0.3048), heightFt: round(o.heightMeters / 0.3048),
    sillFt: round((o.position[1] - o.heightMeters / 2) / 0.3048)
  });
}
out.sort((a, b) => a.face.localeCompare(b.face) || a.along - b.along);
const doc = {
  _readme: "Exterior doors and windows from the Floorplanner twin (design 241952337), registered into A-1 plan px through site-context.json matrix3x2 (RMS 0.54 m). `along` = plan x for faces running along x, plan y for faces running along y. Generated by tools/build-facade-openings.mjs — do not hand-edit.",
  source: md.source, count: out.length, openings: out
};
fs.writeFileSync(new URL("src/data/facade-openings.json", root), JSON.stringify(doc, null, 1) + "\n");
const tally = {}; for (const o of out) tally[o.face + ":" + o.type] = (tally[o.face + ":" + o.type] || 0) + 1;
console.log(out.length, tally);
