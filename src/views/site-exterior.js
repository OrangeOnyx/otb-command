/* A-5 hosts the existing A-1-register model; A-3 owns permanent records.
   The same-origin package is generated by Vite from the portable viewer source. */
import './site-exterior.css';

export function initSiteExterior() {
  const host = document.getElementById('exteriorHost');
  if (!host || host.firstChild) return;
  const base = import.meta.env.BASE_URL + 'site-twin/';
  host.innerHTML = `
    <div class="ext-intro">
      <p>The complete exterior view: building finishes, individual parking stalls, walkway fixtures and utility locations. Select an object to inspect its A-1 site-register entry.</p>
      <nav class="ext-links" aria-label="Related twin sheets">
        <a class="chip" href="#twin" data-interior>A-3 · Interior plans &amp; asset records →</a>
        <a class="chip" href="#evidence">A-4 · Source plans &amp; photos →</a>
      </nav>
    </div>
    <div class="card ext-model">
      <div class="ext-toolbar">
        <span class="ext-status" role="status">Open A-5 to load the model.</span>
        <div class="ext-actions">
          <a href="${base}model.glb" download="OTB-site-twin.glb">Download 3D model</a>
          <a href="${base}site-register.csv" download>Asset CSV</a>
          <button class="chip" type="button" data-expand aria-pressed="false">Expand view</button>
          <button class="chip" type="button" data-retry hidden>Retry model</button>
        </div>
      </div>
      <div class="ext-frame-host"></div>
    </div>
    <p class="ext-note">Presentation model based on plat, CAD and operator references; locations and finishes still need field verification. Parking: 324 striped = the variance (314 plat-labeled + the 10-stall Johnston row confirmed 9/29/2026). Inspection history, photos and maintenance records are in A-3.</p>`;
  const mount = host.querySelector('.ext-frame-host');
  const status = host.querySelector('.ext-status');
  const retry = host.querySelector('[data-retry]');
  const expand = host.querySelector('[data-expand]');
  const card = host.querySelector('.ext-model');
  let frame = null, timer = null;
  const collapse = () => {
    card.classList.remove('is-expanded');
    expand.textContent = 'Expand view';
    expand.setAttribute('aria-pressed', 'false');
  };
  const unload = () => {
    clearTimeout(timer);
    frame?.remove(); frame = null;
    mount.setAttribute('aria-busy', 'false');
    collapse();
  };
  const load = () => {
    if (frame) return;
    status.textContent = 'Loading exterior model…'; retry.hidden = true;
    mount.setAttribute('aria-busy', 'true');
    frame = document.createElement('iframe');
    frame.title = 'A-5 exterior building and site model';
    frame.src = base + 'index.html?embedded=1';
    mount.append(frame);
    timer = setTimeout(() => {
      status.textContent = 'The model is taking longer than expected. Retry to load it again.';
      retry.hidden = false;
    }, 30000);
  };
  window.addEventListener('message', event => {
    if (!frame || event.source !== frame.contentWindow || event.origin !== location.origin
      || event.data?.type !== 'otb-site-twin-status') return;
    if (!['ready', 'error'].includes(event.data.status)) return;
    clearTimeout(timer); mount.setAttribute('aria-busy', 'false');
    if (event.data.status === 'ready') {
      status.textContent = 'Exterior model ready · select an object to inspect';
      retry.hidden = true;
    } else {
      status.textContent = 'The exterior model could not load. Check WebGL support and retry.';
      retry.hidden = false;
    }
  });
  window.addEventListener('sheetchange', event => {
    if (event.detail?.id === 'exterior') load(); else unload();
  });
  retry.onclick = () => { unload(); load(); };
  expand.onclick = () => {
    const expanded = card.classList.toggle('is-expanded');
    expand.textContent = expanded ? 'Close expanded view' : 'Expand view';
    expand.setAttribute('aria-pressed', String(expanded));
  };
  window.addEventListener('keydown', event => { if (event.key === 'Escape') collapse(); });
  host.querySelector('[data-interior]').addEventListener('click', () => {
    const url = new URL(location.href); url.searchParams.set('layout', 'interior');
    history.replaceState(null, '', url);
  });
  // A direct hash may be routed before the lazy module finishes importing.
  if (document.getElementById('pg-exterior')?.classList.contains('on')) load();
}
